/**
 * Exports ABIs from Foundry's out/ into packages/shared/src/abis/*.ts (`as const`, viem-typed).
 * Usage: pnpm contracts:export   (runs this + sync-addresses)
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const dest = join(root, "packages", "shared", "src", "abis");

/** [solidity file, contract name, exported name] */
const CONTRACTS: [string, string, string][] = [
  ["IdentityRegistry.sol", "IdentityRegistry", "identityRegistryAbi"],
  ["ReputationRegistry.sol", "ReputationRegistry", "reputationRegistryAbi"],
  ["ProviderRegistry.sol", "ProviderRegistry", "providerRegistryAbi"],
  ["SignalBook.sol", "SignalBook", "signalBookAbi"],
  ["OutcomeResolver.sol", "OutcomeResolver", "outcomeResolverAbi"],
  ["PerformanceEscrow.sol", "PerformanceEscrow", "performanceEscrowAbi"],
  ["RevenueRouter.sol", "RevenueRouter", "revenueRouterAbi"],
  ["SignerCreditVerifier.sol", "SignerCreditVerifier", "signerCreditVerifierAbi"],
  ["MockPriceAdapter.sol", "MockPriceAdapter", "mockPriceAdapterAbi"],
  ["MockERC3009.sol", "MockERC3009", "mockErc3009Abi"],
  ["MockERC20.sol", "MockERC20", "erc20Abi"],
];

mkdirSync(dest, { recursive: true });
const index: string[] = [];
for (const [file, name, exportName] of CONTRACTS) {
  const p = join(out, file, `${name}.json`);
  if (!existsSync(p)) throw new Error(`Missing ${p}. Run \`forge build\` in contracts/ first.`);
  const abi = JSON.parse(readFileSync(p, "utf8")).abi;
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by scripts/export-abis.ts. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${exportName} } from "./${name}";`);
}
writeFileSync(join(dest, "index.ts"), `// Generated by scripts/export-abis.ts. Do not edit.\n${index.join("\n")}\n`);
console.log(`exported ${CONTRACTS.length} ABIs to ${dest}`);
